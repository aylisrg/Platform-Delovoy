/**
 * Единый текст проверочного («тест») сообщения для кнопок «Тест каналов» на
 * странице мониторинга. Держим формулировку в одном месте, чтобы любой канал
 * получал одинаковое, узнаваемое сообщение при ручной проверке маршрутизации.
 */

/** Экранирование для parse_mode=HTML (название канала может быть из настроек). */
function escapeHtml(value: unknown): string {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

/**
 * Собирает HTML-текст (`parse_mode: "HTML"`) тестового сообщения для канала.
 * `channelName` экранируется — вызывающему не нужно об этом заботиться.
 */
export function buildChannelTestMessage(channelName: string): string {
  return [
    `✅ Это тестовое сообщение в канал «<b>${escapeHtml(channelName)}</b>» от Бота Деловой.`,
    ``,
    `Всё работает штатно.`,
  ].join("\n");
}
