/**
 * Экранирование пользовательского текста для Telegram `parse_mode: "HTML"`.
 *
 * Telegram принимает ограниченное подмножество HTML, и любая неэкранированная
 * `<` в подставляемом значении либо ломает разметку сообщения, либо позволяет
 * автору значения внедрить свою — вплоть до фишинговой ссылки в админ-чате.
 *
 * Достаточно трёх символов: Telegram Bot API требует экранировать `&`, `<`, `>`
 * и ничего больше — кавычки внутри текстовых узлов он не интерпретирует.
 * Порядок важен: `&` первым, иначе экранируются уже вставленные амперсанды.
 *
 * Канонический дом для этого хелпера — здесь. Локальные копии в
 * `notifications/dispatch/channels/telegram.ts`, `feedback/telegram.ts`,
 * `rental/scheduler.ts`, `backups/notify.ts` и др. были устранены при
 * консолидации (issue #471) — все вызывающие места импортируют отсюда.
 */
export function escapeHtml(value: unknown): string {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}
