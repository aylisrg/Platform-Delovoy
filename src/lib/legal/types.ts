/**
 * Структура опубликованного юридического документа (оферта, политика ПД).
 *
 * Разбираем markdown в собственную структуру, а не рендерим generic-рендерером:
 * ТЗ §4.2 требует у каждого пункта свой `id` вида `p-7-4-2`, висячий отступ
 * номера в жёлобе колонки и оглавление с подсветкой — ничего из этого из
 * `<p>7.4.2. …</p>` не получить.
 */

export type LegalBlock =
  /** Нумерованный пункт: `7.4.2. текст` → id `p-7-4-2`. */
  | { kind: "clause"; number: string; id: string; html: string }
  /** Ненумерованный абзац (преамбула, пояснение после перечня). */
  | { kind: "paragraph"; html: string }
  /** Подзаголовок внутри раздела: `### 8.1. Исполнитель обязан:`. */
  | { kind: "subheading"; id: string; number: string | null; label: string }
  /** Цитата-врезка: `> ☐ Я ознакомлен(а)…` (Приложение № 3). */
  | { kind: "quote"; html: string }
  /** Таблица прайс-листа (Приложение № 2). */
  | { kind: "table"; head: string[]; rows: string[][] };

export type LegalSection = {
  /** Якорь раздела: `p-7`, `pravila`, `pravila-3`. */
  id: string;
  /** Номер раздела как в тексте (`7`), либо null у приложений. */
  number: string | null;
  /** Заголовок без номера: «Изменение, перенос и отмена Бронирования…». */
  title: string;
  /** 1 — раздел документа или корень приложения, 2 — раздел внутри приложения. */
  level: 1 | 2;
  blocks: LegalBlock[];
};

export type LegalDocument = {
  /** `# ПУБЛИЧНАЯ ОФЕРТА` */
  title: string;
  /** `## о заключении договора…` — подзаголовок сразу под h1. */
  subtitle: string | null;
  /** Всё до первого нумерованного раздела. */
  preamble: LegalBlock[];
  sections: LegalSection[];
};
